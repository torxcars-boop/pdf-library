export const recordExamSubmission = (
  currentStats: StudentStats,
  submission: {
    examId: string;
    examTitle: string;
    subject: string;
    score: number;
    totalMarks: number;
    percentage: number;
    passed: boolean;
    timeSpentSeconds: number;
    answers: Record<number, number>;
    feedback: string;
    totalQuestions: number;
    correctQuestions: number;
  }
): StudentStats => {
  const newTotalExams = currentStats.totalExamsTaken + 1;
  const newPassedExams = submission.passed ? currentStats.passedExams + 1 : currentStats.passedExams;
  const newAvgScore = Number(
    (((currentStats.averageScore * currentStats.totalExamsTaken) + submission.percentage) / newTotalExams).toFixed(1)
  );
  const newTotalStudyMinutes = currentStats.totalStudyMinutes + Math.round(submission.timeSpentSeconds / 60);

  const subjectKey = submission.subject;
  const existingSubPerf = currentStats.subjectPerformance[subjectKey] || {
    totalQuestions: 0,
    correctQuestions: 0,
    examsCount: 0,
    averageScore: 0
  };

  const updatedSubPerf = {
    totalQuestions: existingSubPerf.totalQuestions + submission.totalQuestions,
    correctQuestions: existingSubPerf.correctQuestions + submission.correctQuestions,
    examsCount: existingSubPerf.examsCount + 1,
    averageScore: Number(
      (((existingSubPerf.averageScore * existingSubPerf.examsCount) + submission.percentage) / (existingSubPerf.examsCount + 1)).toFixed(1)
    )
  };

  const updatedSubjectPerformance = {
    ...currentStats.subjectPerformance,
    [subjectKey]: updatedSubPerf
  };

  const newSubmission = {
    id: 'sub_' + Date.now(),
    examId: submission.examId,
    examTitle: submission.examTitle,
    subject: submission.subject,
    score: submission.score,
    totalMarks: submission.totalMarks,
    percentage: submission.percentage,
    passed: submission.passed,
    timeSpentSeconds: submission.timeSpentSeconds,
    submittedAt: 'الآن',
    answers: submission.answers,
    feedback: submission.feedback
  };

  const newRecentExams = [newSubmission, ...currentStats.recentExams.slice(0, 9)];

  const updatedAchievements = currentStats.achievements.map(ach => {
    if (ach.id === 'ach-first-exam') {
      return { ...ach, unlocked: true, unlockedAt: 'تم الإنجاز', progress: 100 };
    }
    if (ach.id === 'ach-streak-3') {
      return { ...ach, unlocked: true, unlockedAt: 'تم الإنجاز', progress: 100 };
    }
    if (ach.id === 'ach-chem-pro' && subjectKey === 'كيمياء' && submission.percentage >= 85) {
      return { ...ach, unlocked: true, unlockedAt: 'اليوم', progress: 100 };
    }
    if (ach.id === 'ach-phys-genius' && subjectKey === 'فيزياء' && submission.percentage >= 80) {
      return { ...ach, unlocked: true, unlockedAt: 'اليوم', progress: 100 };
    }
    return ach;
  });

  const updatedStats: StudentStats = {
    ...currentStats,
    totalExamsTaken: newTotalExams,
    passedExams: newPassedExams,
    averageScore: newAvgScore,
    totalStudyMinutes: newTotalStudyMinutes,
    lastActiveDate: new Date().toISOString(),
    recentExams: newRecentExams,
    subjectPerformance: updatedSubjectPerformance,
    achievements: updatedAchievements
  };

  saveStudentStats(updatedStats);
  return updatedStats;
};

// Exam Storage for Admin additions and deletions
const LOCAL_STORAGE_CUSTOM_EXAMS = 'arm_custom_student_exams_v2';
const LOCAL_STORAGE_DELETED_EXAMS = 'arm_deleted_student_exams_v2';

export const getDeletedExamIds = (): string[] => {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_DELETED_EXAMS);
    if (raw) return JSON.parse(raw);
  } catch (e) {
    // fallback
  }
  return [];
};

export const getCustomStudentExams = (): Exam[] => {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_CUSTOM_EXAMS);
    if (raw) return JSON.parse(raw);
  } catch (e) {
    // fallback
  }
  return [];
};

export const getAllStudentExams = (): Exam[] => {
  const deletedIds = new Set(getDeletedExamIds());
  const customExams = getCustomStudentExams();
  
  // Merge custom exams with built-in exams, excluding deleted ones
  const combined = [...customExams, ...EGYPT_STUDENT_EXAMS];
  const uniqueMap = new Map<string, Exam>();
  
  combined.forEach(e => {
    if (!deletedIds.has(e.id) && !uniqueMap.has(e.id)) {
      uniqueMap.set(e.id, e);
    }
  });

  return Array.from(uniqueMap.values());
};

export const addCustomStudentExam = (exam: Exam): Exam[] => {
  try {
    const currentCustom = getCustomStudentExams();
    const updated = [exam, ...currentCustom.filter(e => e.id !== exam.id)];
    localStorage.setItem(LOCAL_STORAGE_CUSTOM_EXAMS, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to add custom exam', e);
  }
  return getAllStudentExams();
};

export const deleteStudentExam = (examId: string): Exam[] => {
  try {
    const deleted = getDeletedExamIds();
    if (!deleted.includes(examId)) {
      deleted.push(examId);
      localStorage.setItem(LOCAL_STORAGE_DELETED_EXAMS, JSON.stringify(deleted));
    }
    const currentCustom = getCustomStudentExams();
    const filtered = currentCustom.filter(e => e.id !== examId);
    localStorage.setItem(LOCAL_STORAGE_CUSTOM_EXAMS, JSON.stringify(filtered));
  } catch (e) {
    console.error('Failed to delete student exam', e);
  }
  return getAllStudentExams();
};
